"""Build ``corpus/`` from the upstream sources checked out under ``sources/``.

Two public benchmarks for JSON Schema inclusion are read at the commits their submodules pin:

1. The containment test suite (Passau, ER 2021): schema pairs generated from the official
   JSON Schema Test Suite with the answer known by construction. Its draft 2020-12 cases are
   taken as they are.
2. The inclusion artifact of "JSON Schema Inclusion through Refutational Normalization"
   (2026): eight datasets of fused tests in older drafts, which are split back into their two
   schemas (``unfuse``) and converted to draft 2020-12 (``convert``).

Every case becomes one folder ``corpus/<collection>/.../<name>/`` holding ``a.json``,
``b.json`` and ``case.json``. The question a case asks is always whether ``a.json`` accepts
every instance valid under ``b.json``. Both upstream sources list the narrower schema first,
so ``b.json`` is upstream's first schema and ``a.json`` its second.

``collections.toml`` names the collections and where each comes from; ``overrides.toml``
lists the cases whose label departs from upstream's. Run from the repository root::

    make sources   # once: check out the upstream submodules
    make corpus
"""

import argparse
import hashlib
import json
import re
import shutil
import subprocess
import tomllib
from collections import Counter
from dataclasses import dataclass, replace
from pathlib import Path
from typing import TYPE_CHECKING, Literal, Self
from urllib.parse import urldefrag, urljoin

from subsumes_benchmark.convert import (
    DRAFT_2020_12,
    VERBATIM_KEYWORDS,
    ConversionError,
    Converter,
    dialect_of,
)
from subsumes_benchmark.unfuse import unfuse

if TYPE_CHECKING:
    from collections.abc import Iterator, Mapping, Sequence

    from subsumes_benchmark import Json
    from subsumes_benchmark.convert import PointerMap

SOURCES = Path("sources")

type LabelOrigin = Literal["by-construction", "witness-generator", "upstream-tests"]

# The directory of a fused test is the artifact's answer to "is S1 included in S2?".
VERDICT_DIRS: Mapping[str, bool | None] = {"sat": False, "unsat": True, "unknown": None}

# File names of the synthesized collection carry the draft, category, keyword and case id of
# the containment test suite they were generated by; they become the path of the case.
SYNTHESIZED_NAME_RE = re.compile(
    r"^(draft4|draft6|draft2019_09)"
    r"_(valid|nonvalid|reflexive|unions|universal|unsatisfiable)"
    r"_(.+?)_id(\d+)_subschema1_not_2$"
)

CASE_SCHEMA: dict[str, Json] = {
    "$schema": DRAFT_2020_12,
    "$id": "https://github.com/georg-wolflein/subsumes-benchmark/blob/main/corpus/case.schema.json",
    "title": "A JSON Schema inclusion benchmark case",
    "description": (
        "What is known about the two schemas next to this file: does a.json accept every "
        "instance valid under b.json? The labels hold for draft 2020-12 with format asserted "
        "and patterns read in the dialect of the Rust regex crate."
    ),
    "type": "object",
    "required": ["a_subsumes_b", "b_subsumes_a", "upstream"],
    "additionalProperties": False,
    "properties": {
        "a_subsumes_b": {
            "type": ["boolean", "null"],
            "description": (
                "Whether a.json accepts every instance valid under b.json; null when the "
                "corpus claims nothing."
            ),
        },
        "b_subsumes_a": {
            "type": ["boolean", "null"],
            "description": "The same question in the other direction.",
        },
        "upstream": {
            "type": "string",
            "description": (
                "The file this case comes from, as a path inside the source repository that "
                "collection.json names; the test suite's cases add the case id after a '#'."
            ),
        },
        "note": {
            "type": "string",
            "description": "Why the labels depart from upstream's; absent when they do not.",
        },
    },
}


class ConfigError(Exception):
    pass


def git(*args: str) -> str:
    return subprocess.run(["git", *args], check=True, capture_output=True, text=True).stdout.strip()


@dataclass(frozen=True)
class Source:
    """An upstream repository, checked out as a submodule under ``sources/``."""

    name: str
    root: Path
    repository: str
    commit: str
    license: str
    license_file: Path

    @classmethod
    def create(cls, name: str, spec: Mapping[str, str]) -> Self:
        root = SOURCES / name
        if not (root / spec["license-file"]).exists():
            raise ConfigError(f"{root} is not checked out; run `make sources`")
        return cls(
            name=name,
            root=root,
            repository=git("config", "-f", ".gitmodules", "--get", f"submodule.{root}.url"),
            commit=git("-C", str(root), "rev-parse", "HEAD"),
            license=spec["license"],
            license_file=root / spec["license-file"],
        )


@dataclass(frozen=True)
class Collection:
    """A named part of the corpus, built from one dataset of one source."""

    name: str
    source: Source
    path: str
    labels: LabelOrigin
    use_case: str
    description: str

    @property
    def manifest(self) -> Json:
        return {
            "description": self.description,
            "use_case": self.use_case,
            "labels": self.labels,
            "license": self.source.license,
            "license_file": f"licenses/{self.source.name}.txt",
            "source": {
                "repository": self.source.repository,
                "commit": self.source.commit,
                "path": self.path,
            },
        }


@dataclass(frozen=True)
class Override:
    """The labels a case gets instead of upstream's, and why."""

    note: str
    a_subsumes_b: bool | None
    b_subsumes_a: bool | None


@dataclass(frozen=True)
class Case:
    id: str
    a: Json
    b: Json
    a_subsumes_b: bool | None
    b_subsumes_a: bool | None
    upstream: str
    note: str | None = None

    @property
    def metadata(self) -> Json:
        out: dict[str, Json] = {
            "a_subsumes_b": self.a_subsumes_b,
            "b_subsumes_a": self.b_subsumes_a,
            "upstream": self.upstream,
        }
        if self.note is not None:
            out["note"] = self.note
        return out


def load_collections(path: Path) -> list[Collection]:
    config = tomllib.loads(path.read_text(encoding="utf-8"))
    sources = {name: Source.create(name, spec) for name, spec in config["sources"].items()}
    return [
        Collection(
            name=name,
            source=sources[spec["source"]],
            path=spec["path"],
            labels=spec["labels"],
            use_case=spec["use-case"],
            description=spec["description"],
        )
        for name, spec in config["collections"].items()
    ]


def load_overrides(path: Path) -> dict[str, Override]:
    """The override of every case ``overrides.toml`` lists, by case id."""
    overrides: dict[str, Override] = {}
    for entry in tomllib.loads(path.read_text(encoding="utf-8")).get("override", []):
        unknown = entry.keys() - {"note", "a_subsumes_b", "b_subsumes_a", "cases"}
        if unknown:
            raise ConfigError(f"{path}: unknown keys {sorted(unknown)}")
        override = Override(entry["note"], entry.get("a_subsumes_b"), entry.get("b_subsumes_a"))
        for case_id in entry["cases"]:
            if case_id in overrides:
                raise ConfigError(f"{path}: {case_id} is listed twice")
            overrides[case_id] = override
    return overrides


# --------------------------------------------------------------------------- the containment suite


def read_containment_testsuite(collection: Collection) -> Iterator[Case]:
    tests_dir = collection.source.root / collection.path
    for path in sorted(tests_dir.rglob("*.json")):
        # <category>/<keyword>.json, or <category>/optional/[format/]<keyword>.json for the
        # cases the official suite marks optional (format assertions, big numbers, ...).
        parts = path.relative_to(tests_dir).with_suffix("").parts
        if not (len(parts) == 2 or parts[1] == "optional"):
            raise ConversionError(f"unexpected test suite layout: {path}")
        rel = path.relative_to(collection.source.root).as_posix()
        for case in json.loads(path.read_text(encoding="utf-8")):
            tests = case["tests"]
            yield Case(
                id="/".join((collection.name, *parts, str(case["id"]))),
                a=case["schema2"],
                b=case["schema1"],
                a_subsumes_b=tests.get("s1SubsetEqOfs2"),
                b_subsumes_a=tests.get("s2SubsetEqOfs1"),
                upstream=f"{rel}#{case['id']}",
            )


def read_remotes(source: Source) -> dict[str, Json]:
    """The documents the suite's ``$ref`` cases load, under the URLs the cases use."""
    remotes = source.root / "JSON-Schema-Test-Suite" / "remotes"
    return {
        "http://localhost:1234/" + path.relative_to(remotes).as_posix(): json.loads(
            path.read_text(encoding="utf-8")
        )
        for path in sorted(remotes.rglob("*.json"))
    }


# --------------------------------------------------------------------------- the inclusion artifact


def external_refs(node: Json, base: str, out: set[str]) -> None:
    """Collect absolute URLs (without fragment) of every non-local reference."""
    if isinstance(node, list):
        for item in node:
            external_refs(item, base, out)
    elif isinstance(node, dict):
        for key in ("id", "$id"):
            value = node.get(key)
            if isinstance(value, str) and not value.startswith("#"):
                base = urljoin(base, value) if base else value
        ref = node.get("$ref")
        if isinstance(ref, str) and not ref.startswith("#"):
            out.add(urldefrag(urljoin(base, ref) if base else ref)[0])
        for key, value in node.items():
            if key not in VERBATIM_KEYWORDS:
                external_refs(value, base, out)


def read_external_documents(
    source: Source, collections: Sequence[Collection]
) -> tuple[dict[str, Json], dict[str, PointerMap]]:
    """The documents the artifact's tests reference, transitively, converted to draft 2020-12.

    They come from the artifact's cache, which names each file by the SHA-256 of its URL. The
    pointer maps say where each node of a document moved, for the references into it.
    """
    cache: dict[str, Path] = {}
    for path in (source.root / ".schema-cache").iterdir():
        if match := re.search(r"([0-9a-f]{64})\.json$", path.name):
            cache[match.group(1)] = path
    needed: set[str] = set()
    for collection in collections:
        for path in (source.root / collection.path).rglob("*.json"):
            external_refs(json.loads(path.read_text(encoding="utf-8")), "", needed)
    converted: dict[str, tuple[Converter, Json]] = {}
    pending = sorted(needed)
    while pending:
        url = pending.pop()
        if url in converted:
            continue
        digest = hashlib.sha256(url.encode()).hexdigest()
        if digest not in cache:
            raise ConversionError(f"external reference {url} is not in the artifact's cache")
        raw = json.loads(cache[digest].read_text(encoding="utf-8"))
        more: set[str] = set()
        external_refs(raw, url, more)
        pending.extend(sorted(more - set(converted)))
        converter = Converter()
        schema = converter.convert(raw, base=url)
        if isinstance(schema, dict):
            schema["$id"] = url
        converted[url] = (converter, schema)
    pointer_maps = {url: converter.pmap for url, (converter, _) in converted.items()}
    documents = {
        url: converter.rewrite_refs(schema, pointer_maps)
        for url, (converter, schema) in converted.items()
    }
    return documents, pointer_maps


def case_name(stem: str) -> str:
    """The path of a case inside its collection, from the name of its upstream file."""
    if match := SYNTHESIZED_NAME_RE.match(stem):
        draft, category, keyword, number = match.groups()
        return f"{draft.replace('_', '-')}/{category}/{keyword}/{number}"
    return stem


def read_inclusion(
    collection: Collection,
    pointer_maps: dict[str, PointerMap],
    notes: Counter[str],
    dialects: Counter[str],
) -> Iterator[Case]:
    dataset = collection.source.root / collection.path
    for verdict_dir, included in VERDICT_DIRS.items():
        for path in sorted((dataset / verdict_dir).glob("*.json")):
            try:
                s1, s2, applied = unfuse(json.loads(path.read_text(encoding="utf-8")))
                sides: list[Json] = []
                for raw in (s1, s2):
                    dialects[dialect_of(raw)] += 1
                    converter = Converter()
                    sides.append(converter.rewrite_refs(converter.convert(raw), pointer_maps))
                    applied |= converter.notes
            except ConversionError as exc:
                raise ConversionError(f"{path}: {exc}") from exc
            notes.update(applied)
            yield Case(
                id=f"{collection.name}/{case_name(path.stem)}",
                a=sides[1],
                b=sides[0],
                a_subsumes_b=included,
                b_subsumes_a=None,
                upstream=path.relative_to(collection.source.root).as_posix(),
            )


# --------------------------------------------------------------------------- writing


def write_json(path: Path, data: Json) -> None:
    """Write indented JSON, with every non-ASCII character escaped so that none is invisible."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, allow_nan=False) + "\n", encoding="utf-8")


def write_case(out: Path, case: Case) -> None:
    folder = out / case.id
    write_json(folder / "a.json", case.a)
    write_json(folder / "b.json", case.b)
    write_json(folder / "case.json", case.metadata)


def overridden(cases: Sequence[Case], overrides: Mapping[str, Override]) -> list[Case]:
    """The cases with the labels and notes of their overrides."""
    ids = Counter(case.id for case in cases)
    if duplicates := sorted(i for i, n in ids.items() if n > 1):
        raise ConversionError(f"duplicate case ids: {duplicates}")
    if missing := sorted(overrides.keys() - ids.keys()):
        raise ConfigError(f"overrides.toml lists cases that do not exist: {missing}")
    return [
        replace(
            case,
            a_subsumes_b=override.a_subsumes_b,
            b_subsumes_a=override.b_subsumes_a,
            note=override.note,
        )
        if (override := overrides.get(case.id))
        else case
        for case in cases
    ]


def build(out: Path, collections_file: Path, overrides_file: Path) -> None:
    collections = load_collections(collections_file)
    overrides = load_overrides(overrides_file)
    sources = {c.source.name: c.source for c in collections}
    artifact = [c for c in collections if c.source.name == "inclusion-artifact"]

    resources = read_remotes(sources["containment-testsuite"])
    documents, pointer_maps = read_external_documents(sources["inclusion-artifact"], artifact)
    resources |= documents

    notes: Counter[str] = Counter()
    dialects: Counter[str] = Counter()
    cases: dict[str, list[Case]] = {}
    for collection in collections:
        print(f"reading {collection.name}")
        match collection.source.name:
            case "containment-testsuite":
                cases[collection.name] = list(read_containment_testsuite(collection))
            case "inclusion-artifact":
                cases[collection.name] = list(
                    read_inclusion(collection, pointer_maps, notes, dialects)
                )
            case other:
                raise ConfigError(f"no reader for source {other}")
    final = overridden([case for group in cases.values() for case in group], overrides)

    if out.exists():
        shutil.rmtree(out)
    print(f"writing {len(final)} cases")
    for case in final:
        write_case(out, case)
    for collection in collections:
        write_json(out / collection.name / "collection.json", collection.manifest)
    write_json(out / "resources.json", dict(sorted(resources.items())))
    write_json(out / "case.schema.json", CASE_SCHEMA)
    licenses = {name: source.license_file for name, source in sources.items()} | {
        "json-schema-test-suite": sources["containment-testsuite"].root
        / "JSON-Schema-Test-Suite"
        / "LICENSE"
    }
    for name, path in licenses.items():
        target = out / "licenses" / f"{name}.txt"
        target.parent.mkdir(parents=True, exist_ok=True)
        path.copy(target)

    print(f"\n{'collection':24s} {'cases':>6s} {'true':>6s} {'false':>6s} {'null':>6s}")
    by_id = {case.id: case for case in final}
    for name, group in cases.items():
        labels = Counter(by_id[case.id].a_subsumes_b for case in group)
        print(f"{name:24s} {len(group):6d} {labels[True]:6d} {labels[False]:6d} {labels[None]:6d}")
    print(f"\n{len(resources)} external documents, {len(overrides)} overridden cases")
    print("\nwhat each side of the inclusion artifact declared as its dialect:")
    for dialect, n in dialects.most_common():
        print(f"  {n:6d}  {dialect}")
    print("\nconversions applied, by number of cases:")
    for note, n in notes.most_common():
        print(f"  {n:6d}  {note}")


def main() -> None:
    parser = argparse.ArgumentParser(description="Build the corpus from the upstream sources.")
    parser.add_argument("--out", type=Path, default=Path("corpus"), help="where to write it")
    parser.add_argument("--collections", type=Path, default=Path("collections.toml"))
    parser.add_argument("--overrides", type=Path, default=Path("overrides.toml"))
    args = parser.parse_args()
    build(args.out, args.collections, args.overrides)
